from dataclasses import dataclass

@dataclass(frozen=True)
class GOODS_IN:
    GET_GOODS_IN_ID_BY_SHOP_NOM = """SELECT
        GOODS_IN_ID
    FROM GOODS_IN
    WHERE SHOP_NOMENCLATURE_ID = ? AND IS_SALED = ?
    ORDER BY GOODS_IN_ID DESC;
    """

